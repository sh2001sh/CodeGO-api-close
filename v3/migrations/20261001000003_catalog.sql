    FOR EACH ROW EXECUTE FUNCTION v3_platform.enqueue_invalidation('catalog', 'channel_id');
CREATE TRIGGER channel_models_invalidate AFTER INSERT OR UPDATE OR DELETE ON v3_catalog.channel_models
    FOR EACH ROW EXECUTE FUNCTION v3_platform.enqueue_invalidation('catalog', 'channel_id');
