    FOR EACH ROW EXECUTE FUNCTION v3_platform.enqueue_invalidation('pricing', 'model');
CREATE TRIGGER route_pools_invalidate AFTER INSERT OR UPDATE OR DELETE ON v3_catalog.route_pools
    FOR EACH ROW EXECUTE FUNCTION v3_platform.enqueue_invalidation('catalog', 'id');
