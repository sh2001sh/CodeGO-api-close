CREATE TABLE v3_channelmarket.multiplier_trend_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id text NOT NULL REFERENCES v3_channelmarket.groups(id),
    channel_id bigint NOT NULL REFERENCES v3_catalog.channels(id),
    source_label text NOT NULL,
    models jsonb NOT NULL DEFAULT '[]',
    multiplier_ppm bigint NOT NULL,
    reliable boolean NOT NULL DEFAULT false,
    request_count bigint NOT NULL DEFAULT 0,
    wilson_success_rate double precision NOT NULL DEFAULT 0,
    bucket_started_at timestamptz NOT NULL,
    captured_at timestamptz NOT NULL,
    UNIQUE(group_id,bucket_started_at)
