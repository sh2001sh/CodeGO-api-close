CREATE TRIGGER channelmarket_groups_touch BEFORE UPDATE ON v3_channelmarket.groups FOR EACH ROW EXECUTE FUNCTION v3_platform.touch_updated_at();
CREATE TRIGGER channelmarket_pools_touch BEFORE UPDATE ON v3_channelmarket.route_pools FOR EACH ROW EXECUTE FUNCTION v3_platform.touch_updated_at();
CREATE TRIGGER channelmarket_groups_invalidate AFTER INSERT OR UPDATE OR DELETE ON v3_channelmarket.groups FOR EACH ROW EXECUTE FUNCTION v3_platform.enqueue_invalidation('catalog','id');
CREATE TRIGGER channelmarket_access_invalidate AFTER INSERT OR UPDATE OR DELETE ON v3_channelmarket.group_access FOR EACH ROW EXECUTE FUNCTION v3_platform.enqueue_invalidation('catalog','group_id');
CREATE TRIGGER channelmarket_blocks_invalidate AFTER INSERT OR UPDATE OR DELETE ON v3_channelmarket.channel_user_blocks FOR EACH ROW EXECUTE FUNCTION v3_platform.enqueue_invalidation('catalog','channel_id');
CREATE TRIGGER channelmarket_multipliers_invalidate AFTER INSERT OR UPDATE OR DELETE ON v3_channelmarket.user_multipliers FOR EACH ROW EXECUTE FUNCTION v3_platform.enqueue_invalidation('catalog','channel_id');
CREATE TRIGGER channelmarket_windows_invalidate AFTER INSERT OR UPDATE OR DELETE ON v3_channelmarket.time_range_multipliers FOR EACH ROW EXECUTE FUNCTION v3_platform.enqueue_invalidation('catalog','channel_id');
CREATE TRIGGER channelmarket_pools_invalidate AFTER INSERT OR UPDATE OR DELETE ON v3_channelmarket.route_pools FOR EACH ROW EXECUTE FUNCTION v3_platform.enqueue_invalidation('catalog','id');
