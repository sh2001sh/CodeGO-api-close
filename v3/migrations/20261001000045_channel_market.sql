CREATE TABLE v3_channelmarket.gpt56_mapping_runs (
    id text PRIMARY KEY,
    channel_id bigint NOT NULL REFERENCES v3_catalog.channels(id),
    parent_run_id text,
    level text NOT NULL,
    trigger text NOT NULL,
    status text NOT NULL,
    results jsonb NOT NULL DEFAULT '{}',
    started_at timestamptz NOT NULL,
    completed_at timestamptz,
    created_at timestamptz NOT NULL
);
CREATE TABLE v3_channelmarket.ranking_snapshots (
