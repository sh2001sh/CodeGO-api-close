export type NotificationMessage = keyof typeof notificationMessages

export function useNotificationTranslation() {
  const { locale, t } = useTranslation()
  return {
    t,
    nt: (key: NotificationMessage, parameters?: TranslationParameters) =>
      interpolateTranslation(notificationMessages[key][localeIndex[locale]], parameters),
  }
}
